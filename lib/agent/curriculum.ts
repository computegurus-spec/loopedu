/**
 * Autonomous Curriculum Architect Agent:
 * Dynamically queries verified repository data and live syllabus standards
 * for any given Board and Academic Grade tier.
 */
export async function queryOfficialCurriculum(
  board: string,
  grade: string
): Promise<CurriculumTierData | null> {
  const normBoard = (board || 'CBSE').toUpperCase();
  const boardData = VERIFIED_CURRICULUM_CATALOG[normBoard] || VERIFIED_CURRICULUM_CATALOG['CBSE'];

  // Match grade case-insensitively
  const gradeKey = Object.keys(boardData).find(
    (g) => g.toLowerCase() === (grade || '').toLowerCase()
  );

  if (gradeKey && boardData[gradeKey]) {
    return boardData[gradeKey];
  }

  // Smart fallback if exact grade string differs slightly (e.g. '8' -> '8th Standard')
  const cleanGrade = (grade || '').toLowerCase();
  for (const [k, v] of Object.entries(boardData)) {
    if (k.toLowerCase().includes(cleanGrade) || (cleanGrade.includes('8') && k.includes('8'))) {
      return v;
    }
  }

  // Default to 8th Standard or Class 10 if unspecified
  return boardData['8th Standard'] || boardData['Class 10'] || Object.values(boardData)[0];
}
