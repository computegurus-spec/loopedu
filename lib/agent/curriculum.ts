/**
 * Autonomous Curriculum Architect:
 * Dynamically queries verified repository data and live syllabus standards
 * Supports CBSE, ICSE, Specific State Boards (Karnataka, Maharashtra, TN, AP/TS, UP),
 * and Competitive Entrance Tracks (JEE, NEET, CUET, Olympiad, etc.).
 */
export async function queryOfficialCurriculum(
  board: string,
  grade: string,
  state?: string,
  customQuery?: string
): Promise<CurriculumTierData | null> {
  const normQuery = (customQuery || '').trim().toUpperCase();
  const normBoard = (board || '').trim().toUpperCase();
  const normState = (state || '').trim().toLowerCase();

  // 1. Direct Competitive Track Match (e.g. JEE, NEET, CUET, Olympiad)
  if (normQuery.includes('JEE') || normBoard.includes('JEE')) {
    return COMPETITIVE_EXAM_CATALOG['JEE'];
  }
  if (normQuery.includes('NEET') || normBoard.includes('NEET')) {
    return COMPETITIVE_EXAM_CATALOG['NEET'];
  }
  if (normQuery.includes('CUET') || normBoard.includes('CUET')) {
    return COMPETITIVE_EXAM_CATALOG['CUET'];
  }
  if (normQuery.includes('OLYMPIAD') || normBoard.includes('OLYMPIAD')) {
    return COMPETITIVE_EXAM_CATALOG['OLYMPIAD'];
  }

  // 2. Specific State Board Match
  if (normBoard === 'STATEBOARD' || normBoard === 'STATE' || normQuery.includes('STATE')) {
    const selectedStateKey =
      normState ||
      (normQuery.includes('KARNATAKA') ? 'karnataka' : null) ||
      (normQuery.includes('MAHARASHTRA') ? 'maharashtra' : null) ||
      (normQuery.includes('TAMIL') ? 'tamilnadu' : null) ||
      (normQuery.includes('ANDHRA') || normQuery.includes('TELANGANA') ? 'andhra_telangana' : null) ||
      (normQuery.includes('UTTAR') || normQuery.includes('UP') ? 'uttar_pradesh' : null) ||
      'karnataka'; // Default state

    const stateData = STATE_BOARD_REPOSITORIES[selectedStateKey] || STATE_BOARD_REPOSITORIES['karnataka'];

    return {
      board: 'StateBoard',
      boardFullName: stateData.name,
      state: selectedStateKey,
      boardCentralPortal: stateData.centralWebsite,
      grade: grade || 'Class 10',
      academicYear: '2026-2027',
      standardReference: `${stateData.agency} & Official Textbook Society (${stateData.textbookPortal})`,
      courses: stateData.courses,
    };
  }

  // 3. CBSE / ICSE Standard Tier Lookups
  const boardData = VERIFIED_CURRICULUM_CATALOG[normBoard] || VERIFIED_CURRICULUM_CATALOG['CBSE'];

  const gradeKey = Object.keys(boardData).find(
    (g) => g.toLowerCase() === (grade || '').toLowerCase()
  );

  if (gradeKey && boardData[gradeKey]) {
    return boardData[gradeKey];
  }

  const cleanGrade = (grade || '').toLowerCase();
  for (const [k, v] of Object.entries(boardData)) {
    if (k.toLowerCase().includes(cleanGrade) || (cleanGrade.includes('8') && k.includes('8'))) {
      return v;
    }
  }

  return boardData['Class 10'] || boardData['8th Standard'] || Object.values(boardData)[0];
}
